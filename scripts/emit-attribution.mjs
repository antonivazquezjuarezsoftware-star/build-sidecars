#!/usr/bin/env node
// scripts/emit-attribution.mjs
//
// Writes THIRD-PARTY.md from manifest.json.
//
//   node scripts/emit-attribution.mjs
//   node scripts/emit-attribution.mjs --check   # fail if stale
//
// This repository redistributes binaries it did not build. Now that it is
// public that is *conveying* them, and the GPL-licensed ones (ffmpeg/ffprobe)
// come with an obligation to say where the corresponding source is. Generated
// rather than written by hand for the usual reason: a hand-maintained list of
// 16 entries stops matching what is actually published on the first release
// nobody remembers to edit it for.

import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join, resolve } from 'path'
import { fileURLToPath } from 'url'

import { REPO_SLUG } from '../sidecars.config.mjs'
import { readManifest } from './lib/manifest.mjs'
import { logger, parseArgs } from './lib/log.mjs'

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..')
const log = logger('emit-attribution')

// Where the *source* for each upstream provider lives. Keyed by license so a
// new artifact under a known license is covered without editing this table.
const SOURCE_NOTES = {
  'GPL-3.0-or-later': [
    'ffmpeg and ffprobe are distributed under the GNU General Public License v3',
    'or later. The corresponding source is published by the upstream builders:',
    '',
    '- BtbN/FFmpeg-Builds (`master-*` assets) — build scripts at',
    '  <https://github.com/BtbN/FFmpeg-Builds>, ffmpeg source at',
    '  <https://github.com/FFmpeg/FFmpeg>. These are snapshots of `master`; the',
    '  exact revision for a given build is recorded in the upstream release the',
    '  `sourceUrl` below points at.',
    '- eugeneware/ffmpeg-static and evermeet.cx (tagged versions, e.g. `6.1.1`,',
    '  `9.0.1`) — the corresponding ffmpeg source is the matching tag at',
    '  <https://github.com/FFmpeg/FFmpeg/tags>.',
  ],
  'LGPL-2.1-or-later': [
    'libmpv is distributed under the GNU Lesser General Public License v2.1 or',
    'later. Source: <https://github.com/mpv-player/mpv>. Windows build scripts:',
    '<https://github.com/shinchiro/mpv-winbuild-cmake>.',
  ],
  Unlicense: ['yt-dlp is released into the public domain. Source: <https://github.com/yt-dlp/yt-dlp>.'],
}

function render(manifest) {
  const licenses = [...new Set(manifest.artifacts.map((entry) => entry.license))].sort()

  const rows = manifest.artifacts
    .slice()
    .sort((a, b) => a.id.localeCompare(b.id) || a.platform.localeCompare(b.platform))
    .map(
      (entry) =>
        `| \`${entry.id}\` | ${entry.platform} | ${entry.version} | ${entry.license} | ` +
        `[upstream](${entry.sourceUrl}) | \`${entry.sha256.slice(0, 16)}…\` |`,
    )
    .join('\n')

  const notes = licenses
    .map((license) => {
      const lines = SOURCE_NOTES[license]
      if (!lines) {
        return `### ${license}\n\n**No source note recorded for this license — add one to \`scripts/emit-attribution.mjs\`.**`
      }
      return `### ${license}\n\n${lines.join('\n')}`
    })
    .join('\n\n')

  return `<!-- GENERATED by scripts/emit-attribution.mjs — do not edit by hand. -->

# Third-party binaries

This repository redistributes unmodified binaries built by other projects, so
that builds here stop depending on single-maintainer hosts serving mutable
\`latest\` URLs. Nothing in this repository is compiled from source; the assets
attached to release \`${manifest.tag}\` are byte-for-byte what the upstream
providers published, and every one of them is recorded below with the checksum
consumers verify before installing it.

## Written offer for source

For any GPL- or LGPL-licensed binary published here, the corresponding source
is available at the upstream locations named below. If a link has rotted, open
an issue on ${REPO_SLUG} and the source will be provided.

${notes}

## Artifacts (\`${manifest.tag}\`)

| Artifact | Platform | Version | License | Source | sha256 |
| --- | --- | --- | --- | --- | --- |
${rows}

Full checksums, sizes and detected binary formats are in
[\`manifest.json\`](manifest.json).
`
}

function main() {
  const flags = parseArgs(process.argv.slice(2))
  const manifest = readManifest(join(ROOT, 'manifest.json'))
  const target = join(ROOT, 'THIRD-PARTY.md')
  const rendered = render(manifest)
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null

  if (current === rendered) {
    log.info('THIRD-PARTY.md up to date')
    return
  }
  if (flags.check) throw new Error('THIRD-PARTY.md is stale — run: node scripts/emit-attribution.mjs')

  writeFileSync(target, rendered, 'utf8')
  log.ok(`wrote ${target}`)
}

try {
  main()
} catch (error) {
  log.fail(error.message)
  process.exit(1)
}
